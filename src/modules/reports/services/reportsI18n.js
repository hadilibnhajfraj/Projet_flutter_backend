function normLang(lang) {
  return lang === "en" ? "en" : "fr";
}

function makeT(lang) {
  const d = DICT[normLang(lang)];
  return (key, params) => {
    let s = d[key];
    if (s == null) return key;
    if (params) {
      for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };
}

